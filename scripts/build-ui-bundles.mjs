import fs from 'node:fs';
import path from 'node:path';

const read = p => fs.readFileSync(p, 'utf8').trimEnd();

function writeBundle(target, sources, append = '') {
  const banner = `/* Generated by scripts/build-ui-bundles.mjs — edit source files, not this bundle. */`;
  const parts = sources.map(p => `/* source: ${p} */\n${read(p)}`);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, [banner, ...parts, append.trim()].filter(Boolean).join('\n\n') + '\n');
  console.log(`KOSIF_UI_BUNDLE_OK ${target} <= ${sources.join(', ')}`);
}

